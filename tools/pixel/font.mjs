/* ---- baking ------------------------------------------------------------- */

function glyphWidth(entry) {
  return Math.max(...entry[1].map((r) => r.length));
}

/**
 * Bake a glyph table into an atlas: a white-on-transparent mask laid out on a
 * fixed cell grid, plus the metrics the runtime needs to walk it.
 *
 * Fixed cells (rather than a packed strip) are deliberate — the runtime can
 * compute a source rect with two multiplies and no lookup table, which keeps
 * text drawing cheap enough to run every frame on a phone.
 */
export function bakeFont(table, { cellW, cellH, cols = 16, gap = 1, name }) {
  const codes = [];
  for (const ch of Object.keys(table)) codes.push(ch.codePointAt(0));
  const min = Math.min(...codes, 32);
  const max = Math.max(...codes);
  const count = max - min + 1;
  const rows = Math.ceil(count / cols);

  const atlas = new Surface(cols * cellW, rows * cellH);
  const advance = new Array(count).fill(0);
  const white = [248, 248, 248];

  for (let i = 0; i < count; i++) {
    const ch = String.fromCodePoint(min + i);
    const entry = table[ch];
    if (!entry) continue;
    const [yOff, glyphRows] = entry;
    const w = glyphWidth(entry);
    if (w > cellW) throw new Error(`${name}: glyph "${ch}" is ${w}px, cell is ${cellW}px`);
    if (yOff + glyphRows.length > cellH) {
      throw new Error(`${name}: glyph "${ch}" overflows the ${cellH}px cell`);
    }
    const cx = (i % cols) * cellW;
    const cy = Math.floor(i / cols) * cellH;
    glyphRows.forEach((row, j) => {
      for (let x = 0; x < row.length; x++) {
        if (row[x] === "#") atlas.px(cx + x, cy + yOff + j, white);
      }
    });
    advance[i] = ch === " " ? 3 + gap : w + gap;
  }

  return {
    surface: atlas,
    metrics: { name, cellW, cellH, cols, first: min, count, advance, lineHeight: cellH },
  };
}

/** Width of a string in this face — same arithmetic the runtime uses. */
export function measure(metrics, text) {
  let w = 0;
  for (const ch of text) {
    const i = ch.codePointAt(0) - metrics.first;
    w += i >= 0 && i < metrics.count ? metrics.advance[i] : 0;
  }
  return Math.max(0, w - 1);
}

