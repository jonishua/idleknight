/* =========================================================================
   font.mjs — two original bitmap faces for the pixel layer.

   reference/ffvi-art.md §3c measures the SNES face and names the trait every
   retro-web attempt gets wrong:

     7 px cap height · 6 px x-height · 8 px cell
     2 PX VERTICAL STEMS — it is chunky, not a hairline 8x8 font
     proportional advances, 4-10 px
     a hard 1 px (+1,+1) black shadow on every glyph, no blur, no alpha

   Every glyph below is drawn to those metrics and every stem is two pixels
   wide. The shapes are ours. The shadow is NOT baked in — the atlas is a
   white mask so the runtime can tint it (white body / gold labels / violet
   "ready") and stamp the shadow by blitting the same mask in black at +1,+1.

   Authoring format:  char: [yOffset, [ ...rows ]]
   '#' is ink, '.' is nothing. Row 0 of the cell is the cap line; the baseline
   sits under row 6, so ascenders start at y=0, x-height letters at y=1, and
   descenders run to y=8.
   ========================================================================= */

